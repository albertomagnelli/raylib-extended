/*******************************************************************************************
*
*   raylib-extended [skydome] - example 05: day/night skydome with drifting clouds and stars
*
*   A full screen sky pass: a single triangle, no geometry at all, every pixel reconstructs its
*   world space view direction from the inverse view projection matrix. The sky itself is built
*   from five layers, from far to near:
*
*       1. Atmosphere: analytic gradient (zenith/horizon) blended between night, dusk and day
*          keyframes from the sun elevation, plus a warm glow around the sun near the horizon
*       2. Sun and moon: discs with a soft halo, both fading below the horizon
*       3. Stars: two hashed layers of point stars on the rotated view direction. The whole field
*          turns around a tilted celestial pole, so the stars wander through the night like a
*          real sky
*       4. Clouds: a 3D noise volume rendered by marching a ray through a cloud slab, lit by two
*          density probes towards the sun (cheap self shadowing). The noise is sampled with a
*          wind offset that grows with time and a slowly changing third coordinate, so the clouds
*          both move and change shape
*       5. HUD with the time of day and the cloud coverage, drawn with a real TTF at its native
*          size (the scaled 10 pixel default font looks blocky)
*
*   The cloud noise is a tileable 3D volume (periodic gradient noise + periodic Worley cells),
*   generated by a compute shader into a 128x128x128 RGBA16F texture. Periodic hashing is what
*   keeps the cloud plane seamless in every direction.
*
*   DEPENDENCIES:
*       raylib 6.5+   - Window/GL context, Image for the screenshots
*       rlgl + glad   - raw OpenGL 4.6 (compute shader, 3D texture, DSA)
*       glm           - matrices for the ray reconstruction
*
*   WARNING: Requires OpenGL 4.6 support:
*       cmake -B build -DOPENGL_VERSION=4.6
*
*   Controls:
*       LEFT / RIGHT  : Scrub the time of day (+-0.5 h)
*       SPACE         : Pause/resume the automatic day night cycle
*       N / D         : Jump to midnight / noon
*       C             : Toggle the clouds
*       S             : Save a screenshot (skydome_manual.png)
*       MOUSE (RMB)   : Look around
*       ESC           : Close the window
*
*   The --auto mode drives the time of day and the star angle by hand, checks the rendered
*   pixels (day is bright and blue, dusk is red, night is dark, stars are visible and move,
*   clouds are visible and change) and saves four screenshots.
*
********************************************************************************************/

