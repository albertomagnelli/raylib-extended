static i32 checkFailures = 0;

// Smoothstep on the CPU side, used to fade the stars with the sun elevation
static f32 SmoothStep(const f32 edge0, const f32 edge1, const f32 value)
{
    const f32 t = Clamp((value - edge0)/(edge1 - edge0), 0.0f, 1.0f);

    return t*t*(3.0f - 2.0f*t);
}

// Print a self check line and count the failures
static void PrintCheck(const bool ok, const char *format, ...)
{
    char buffer[512] = { 0 };

    va_list args;
    va_start(args, format);
    vsnprintf(buffer, sizeof(buffer), format, args);
    va_end(args);

    if (!ok) checkFailures++;

    printf("%s  %s\n", ok? "PASS" : "FAIL", buffer);
}

static GLuint CompileShader(const GLenum type, const char *code)
{
    const GLuint shader = glCreateShader(type);

    glShaderSource(shader, 1, &code, nullptr);
    glCompileShader(shader);

    GLint compiled = 0;
    glGetShaderiv(shader, GL_COMPILE_STATUS, &compiled);

    if (compiled == 0)
    {
        char log[4096] = { 0 };
        glGetShaderInfoLog(shader, sizeof(log), nullptr, log);

        printf("ERROR: shader compilation failed (%s)\n%s\n", (type == GL_VERTEX_SHADER)? "vertex" : "fragment", log);

        glDeleteShader(shader);
        return 0;
    }

    return shader;
}

static GLuint LinkProgram(const GLuint vertexShader, const GLuint fragmentShader)
{
    const GLuint program = glCreateProgram();

    glAttachShader(program, vertexShader);
    glAttachShader(program, fragmentShader);
    glLinkProgram(program);

    GLint linked = 0;
    glGetProgramiv(program, GL_LINK_STATUS, &linked);

    if (linked == 0)
    {
        char log[4096] = { 0 };
        glGetProgramInfoLog(program, sizeof(log), nullptr, log);

        printf("ERROR: program link failed\n%s\n", log);

        glDeleteProgram(program);
        return 0;
    }

    return program;
}

//----------------------------------------------------------------------------------
// Cloud noise: tileable 3D volume generated by a compute shader, mip mapped
//----------------------------------------------------------------------------------
static GLuint CreateCloudNoiseTexture()
{
    const GLuint computeShader = CompileShader(GL_COMPUTE_SHADER, noiseComputeShaderCode);

    if (computeShader == 0) return 0;

    const GLuint program = glCreateProgram();
    glAttachShader(program, computeShader);
    glLinkProgram(program);

    GLint linked = 0;
    glGetProgramiv(program, GL_LINK_STATUS, &linked);

    glDeleteShader(computeShader);

    if (linked == 0)
    {
        char log[4096] = { 0 };
        glGetProgramInfoLog(program, sizeof(log), nullptr, log);

        printf("ERROR: cloud noise compute program failed\n%s\n", log);
        glDeleteProgram(program);

        return 0;
    }

    // Full mip chain, the cloud shader samples the volume at up to six times its base frequency
    const i32 mipLevels = 1 + static_cast<i32>(floorf(log2f(static_cast<f32>(CLOUD_NOISE_SIZE))));

    GLuint texture = 0;
    glCreateTextures(GL_TEXTURE_3D, 1, &texture);
    glTextureStorage3D(texture, mipLevels, GL_RGBA16F, CLOUD_NOISE_SIZE, CLOUD_NOISE_SIZE, CLOUD_NOISE_SIZE);

    glTextureParameteri(texture, GL_TEXTURE_MIN_FILTER, GL_LINEAR_MIPMAP_LINEAR);
    glTextureParameteri(texture, GL_TEXTURE_MAG_FILTER, GL_LINEAR);
    glTextureParameteri(texture, GL_TEXTURE_WRAP_S, GL_REPEAT);
    glTextureParameteri(texture, GL_TEXTURE_WRAP_T, GL_REPEAT);
    glTextureParameteri(texture, GL_TEXTURE_WRAP_R, GL_REPEAT);

    glUseProgram(program);
    glBindImageTexture(0, texture, 0, GL_TRUE, 0, GL_WRITE_ONLY, GL_RGBA16F);

    glUniform1i(glGetUniformLocation(program, "u_size"), CLOUD_NOISE_SIZE);
    glUniform1i(glGetUniformLocation(program, "u_fbmPeriod"), 6);
    glUniform1i(glGetUniformLocation(program, "u_worleyPeriod"), 12);

    const i32 groups = (CLOUD_NOISE_SIZE + 7)/8;
    glDispatchCompute(groups, groups, groups);
    glMemoryBarrier(GL_TEXTURE_UPDATE_BARRIER_BIT | GL_TEXTURE_FETCH_BARRIER_BIT);

    glUseProgram(0);
    glDeleteProgram(program);

    glGenerateTextureMipmap(texture);

    return texture;
}

//----------------------------------------------------------------------------------
// Sky setup
//----------------------------------------------------------------------------------
static SkyProgram CreateSkyProgram()
{
    SkyProgram sky = { };

    const GLuint vertexShader = CompileShader(GL_VERTEX_SHADER, skyVertexShaderCode);
    const GLuint fragmentShader = CompileShader(GL_FRAGMENT_SHADER, skyFragmentShaderCode);

    if ((vertexShader == 0) || (fragmentShader == 0))
    {
        glDeleteShader(vertexShader);
        glDeleteShader(fragmentShader);

        return sky;
    }

    sky.program = LinkProgram(vertexShader, fragmentShader);

    glDeleteShader(vertexShader);
    glDeleteShader(fragmentShader);

    if (sky.program == 0) return sky;

    sky.invViewProj = glGetUniformLocation(sky.program, "u_invViewProj");
    sky.cameraPosition = glGetUniformLocation(sky.program, "u_cameraPosition");
    sky.sunDirection = glGetUniformLocation(sky.program, "u_sunDirection");
    sky.moonDirection = glGetUniformLocation(sky.program, "u_moonDirection");
    sky.time = glGetUniformLocation(sky.program, "u_time");
    sky.starAngle = glGetUniformLocation(sky.program, "u_starAngle");
    sky.cloudNoise = glGetUniformLocation(sky.program, "u_cloudNoise");
    sky.cloudCoverage = glGetUniformLocation(sky.program, "u_cloudCoverage");
    sky.cloudOpacity = glGetUniformLocation(sky.program, "u_cloudOpacity");
    sky.cloudScale = glGetUniformLocation(sky.program, "u_cloudScale");
    sky.cloudWind = glGetUniformLocation(sky.program, "u_cloudWind");
    sky.cloudSteps = glGetUniformLocation(sky.program, "u_cloudSteps");
    sky.starsStrength = glGetUniformLocation(sky.program, "u_starsStrength");

    return sky;
}

// Sun and moon travel on a circle that is tilted by 55 degrees, the star field uses its own angle
static void ComputeSunDirection(const f32 timeOfDay, vec3 &sunDirection, vec3 &moonDirection)
{
    const f32 angle = (timeOfDay - 6.0f)/24.0f*2.0f*PI;      // 6 h sunrise, 12 h noon, 18 h sunset

    const vec3 east = vec3{ 1.0f, 0.0f, 0.0f };
    const vec3 tiltedUp = vec3{ 0.0f, 0.82f, 0.57f };        // Maximum elevation of about 55 degrees

    sunDirection = normalize(cosf(angle)*east + sinf(angle)*tiltedUp);
    moonDirection = normalize(-sunDirection + vec3{ 0.18f, 0.22f, -0.12f });
}

static glm::mat4 BuildInverseViewProjection(const vec3 &position, const f32 yaw, const f32 pitch)
{
    const vec3 forward = vec3{ sinf(yaw)*cosf(pitch), sinf(pitch), cosf(yaw)*cosf(pitch) };

    const glm::mat4 view = glm::lookAt(glm::vec3(position), glm::vec3(position + forward), glm::vec3(0.0f, 1.0f, 0.0f));
    const glm::mat4 projection = glm::perspective(55.0f*PI/180.0f, static_cast<f32>(WINDOW_WIDTH)/WINDOW_HEIGHT, 1.0f, 200000.0f);

    return glm::inverse(projection*view);
}

// One full screen triangle, every pixel reconstructs its own view ray
static void DrawSky(const SkyProgram &sky, const GLuint emptyVertexArray, const GLuint cloudNoise, const SkyState &state, const vec3 &cameraPosition, const f32 yaw, const f32 pitch)
{
    vec3 sunDirection(0.0f);
    vec3 moonDirection(0.0f);
    ComputeSunDirection(state.timeOfDay, sunDirection, moonDirection);

    const glm::mat4 inverseViewProjection = BuildInverseViewProjection(cameraPosition, yaw, pitch);

    // Use the rlgl entry points instead of raw gl* calls: rlgl caches the GL state, and a raw
    // glDisable(GL_BLEND) leaves its cache out of sync, so the HUD glyphs lose their alpha mask
    rlDisableDepthTest();
    rlDisableBackfaceCulling();
    rlSetBlendMode(BLEND_ALPHA);        // The sky writes alpha 1.0, this changes nothing but keeps the state valid

    glUseProgram(sky.program);

    glUniformMatrix4fv(sky.invViewProj, 1, GL_FALSE, glm::value_ptr(inverseViewProjection));
    glUniform3f(sky.cameraPosition, cameraPosition.x, cameraPosition.y, cameraPosition.z);
    glUniform3f(sky.sunDirection, sunDirection.x, sunDirection.y, sunDirection.z);
    glUniform3f(sky.moonDirection, moonDirection.x, moonDirection.y, moonDirection.z);
    glUniform1f(sky.time, state.animationTime);
    glUniform1f(sky.starAngle, state.starAngle);
    glUniform1f(sky.cloudCoverage, state.cloudCoverage);
    glUniform1f(sky.cloudOpacity, state.cloudOpacity);
    glUniform1f(sky.cloudScale, 1500.0f);
    glUniform2f(sky.cloudWind, 0.35f, -0.22f);
    glUniform1i(sky.cloudSteps, CLOUD_STEPS);
    glUniform1f(sky.starsStrength, 1.0f - SmoothStep(-0.10f, 0.02f, sunDirection.y));

    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_3D, cloudNoise);
    glUniform1i(sky.cloudNoise, 0);

    glBindVertexArray(emptyVertexArray);
    glDrawArrays(GL_TRIANGLES, 0, 3);

    glBindVertexArray(0);
    glUseProgram(0);
}
