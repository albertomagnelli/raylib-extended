//----------------------------------------------------------------------------------
// Cloud noise compute shader: tileable 3D fBm and Worley cells
//----------------------------------------------------------------------------------
static const char *noiseComputeShaderCode = R"(
#version 430 core

layout(local_size_x = 8, local_size_y = 8, local_size_z = 8) in;

layout(binding = 0, rgba16f) writeonly uniform image3D imgNoise;

uniform int u_size;             // Volume resolution (128)
uniform int u_fbmPeriod;        // Lattice period of the first fBm octave (cells per volume)
uniform int u_worleyPeriod;     // Lattice period of the big Worley cells

// PCG style hash, the lattice cell is wrapped by the period so the volume tiles seamlessly
uvec3 HashCell(ivec3 cell, int period)
{
    ivec3 wrapped = ivec3(mod(vec3(cell), vec3(float(period))));
    uint x = uint(wrapped.x + period)*1597334677u ^ uint(wrapped.y + period)*3812015801u ^ uint(wrapped.z + period)*2798796415u;

    x = (x ^ (x >> 17u))*0xed5ad4bbu;
    x = (x ^ (x >> 11u))*0xac4c1b51u;
    x = x ^ (x >> 15u);

    return uvec3(x*73856093u, x*19349663u, x*83492791u);
}

float Hash01(uvec3 h)
{
    return float((h.x >> 8u) & 0x00ffffffu)/16777215.0;
}

// Periodic gradient noise, the gradients are random unit vectors on the lattice
float PeriodicGradientNoise(vec3 position, int period)
{
    vec3 cell = floor(position);
    vec3 offset = position - cell;
    vec3 weight = offset*offset*(3.0 - 2.0*offset);

    float sum = 0.0;

    for (int corner = 0; corner < 8; corner++)
    {
        vec3 cornerOffset = vec3(float(corner & 1), float((corner >> 1) & 1), float((corner >> 2) & 1));
        uvec3 hash = HashCell(ivec3(cell) + ivec3(cornerOffset), period);

        vec3 gradient = normalize(vec3(Hash01(hash), Hash01(hash.yzx), Hash01(hash.zxy))*2.0 - 1.0);
        vec3 cornerWeight = mix(1.0 - weight, weight, cornerOffset);

        sum += dot(gradient, offset - cornerOffset)*cornerWeight.x*cornerWeight.y*cornerWeight.z;
    }

    return sum;
}

// Four octaves of periodic gradient noise, the period doubles with every octave
float PeriodicFbm(vec3 position)
{
    float sum = 0.0;
    float amplitude = 1.0;
    float amplitudeSum = 0.0;
    float frequency = 1.0;

    for (int octave = 0; octave < 4; octave++)
    {
        sum += PeriodicGradientNoise(position*frequency, int(float(u_fbmPeriod)*frequency))*amplitude;
        amplitudeSum += amplitude;
        amplitude *= 0.5;
        frequency *= 2.0;
    }

    return clamp(sum/amplitudeSum*1.45 + 0.5, 0.0, 1.0);
}

// Periodic Worley F1 distance, the feature points sit at hashed positions inside every cell
float PeriodicWorley(vec3 position, int period)
{
    vec3 cell = floor(position);
    vec3 offset = position - cell;

    float minimum = 1.0;

    for (int z = -1; z <= 1; z++)
    {
        for (int y = -1; y <= 1; y++)
        {
            for (int x = -1; x <= 1; x++)
            {
                vec3 neighbour = vec3(float(x), float(y), float(z));
                uvec3 hash = HashCell(ivec3(cell) + ivec3(neighbour), period);

                vec3 feature = vec3(Hash01(hash), Hash01(hash.yzx ^ 0x9e3779b9u), Hash01(hash.zxy ^ 0x85ebca6bu));
                vec3 difference = neighbour + feature - offset;

                minimum = min(minimum, length(difference));
            }
        }
    }

    return clamp(minimum, 0.0, 1.0);
}

void main()
{
    ivec3 texel = ivec3(gl_GlobalInvocationID);

    if ((texel.x >= u_size) || (texel.y >= u_size) || (texel.z >= u_size)) return;

    vec3 uv = (vec3(texel) + 0.5)/float(u_size);

    // R: soft fBm for the cloud body, G: big billows, B: small billows for the edges
    float fbm = PeriodicFbm(uv*float(u_fbmPeriod));
    float bigBillow = 1.0 - PeriodicWorley(uv*float(u_worleyPeriod), u_worleyPeriod);
    float smallBillow = 1.0 - PeriodicWorley(uv*float(u_worleyPeriod*3), u_worleyPeriod*3);

    imageStore(imgNoise, texel, vec4(fbm, bigBillow, smallBillow, 1.0));
}
)";

